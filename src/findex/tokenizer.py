import re
import unicodedata
from typing import Generator

# Регулярний вираз для токенів:
# \b\w+ — починається зі слова/числа
# (?:['’`\-]\w+)* — дозволяє внутрішні апострофи або дефіси (don't, клієнт-сервер)
# \b — межа слова
TOKEN_PATTERN = re.compile(r"\b\w+(?:['’`\-]\w+)*\b", re.UNICODE)


def tokenize(text: str) -> Generator[str, None, None]:
    """
    Потоковий (лінивий) токенізатор тексту.

    Правила токенізації:
    1. Unicode-нормалізація:
       - Текст нормалізується за стандартом NFKC (unicodedata.normalize).
       - Усі символи переводяться у нижній регістр (case-folding) через .lower().
    2. Апострофи:
       - Типографські, прямі та машинні апострофи (’ , ` , ') зводяться
         до єдиного канонічного вигляду `'`.
       - Слова з апострофом всередині не розбиваються (наприклад: "don't", "м'яч").
    3. Дефіси:
       - Внутрішньослівні дефіси зберігаються як частина слова ("клієнт-серверний", "high-tech").
       - Тире та мінуси, оточені пробілами, відкидаються.
    4. Цифри та пунктуація:
       - Окремі числа та послідовності цифр вважаються валідними токенами ("2026", "42").
       - Усі розділові знаки (коми, крапки, знаки оклику тощо) відсікаються.

    Yields:
        str: Послідовність очищених токенів по одному за раз.
    """
    normalized = unicodedata.normalize("NFKC", text).lower()
    canonical = normalized.replace("’", "'").replace("`", "'")

    for match in TOKEN_PATTERN.finditer(canonical):
        yield match.group(0)
